"""End-to-end mimic pipeline smoke on the Newton mjwarp backend, all four solver modes.

Reuses the PhysX-recorded nucleus source dataset (the 'imported demos' path). Two independent
exercises of the pipeline live here:

- ``test_annotate_and_generate_on_newton``: annotate with retry-replay under Newton dynamics, then
  generate a small batch. Cross-backend open-loop replay of the recorded actions yields 0/10 in all
  four solver modes, which xfails before the generate stage ever runs (see its docstring/report).
- ``test_generate_on_newton``: sidesteps that by annotating once under PhysX (``physx_annotated_dataset``
  fixture, known-good) and feeding that source straight into ``generate_dataset.py`` on Newton, so the
  generate stage actually executes on Newton for the first time.
"""

from isaaclab.app import AppLauncher

# launch omniverse app
simulation_app = AppLauncher(headless=True).app

import json
import os
import re
import sys
import tempfile

import h5py
import pytest
from mimic_test_utils import run_script

from isaaclab.utils.assets import ISAACLAB_NUCLEUS_DIR, retrieve_file_path

TASK = "Isaac-Stack-Cube-Franka-IK-Rel-Mimic-v0"
NUCLEUS_DATASET_PATH = os.path.join(ISAACLAB_NUCLEUS_DIR, "Tests", "Mimic", "dataset.hdf5")
DATASETS_DOWNLOAD_DIR = tempfile.mkdtemp(suffix="_newton_mimic_smoke")
_SUBPROCESS_TIMEOUT = 5000
# generate_dataset with generation_guarantee=True loops until enough *successes* are recorded.
# env_loop (generation.py) now self-terminates a zero-success run once num_failures reaches
# datagen_config.max_num_failures (25 for the franka stack cfg), so this no longer needs to be a
# multi-hour bound -- it is a safety net for a genuine hang/crash. See test_generate_on_newton for
# how a timeout-kill is still disambiguated from a real crash, belt-and-suspenders.
_GENERATION_SUBPROCESS_TIMEOUT = 900

SOLVER_MODES = ["mujoco", "mujoco-adaptive", "sap", "sap-adaptive"]

# Matches the env_loop counter line, e.g. "2/2 (100.0%) successful demos generated by mimic".
_SUCCESS_COUNTER_RE = re.compile(r"^(\d+)/(\d+) \([\d.]+%\) successful demos generated by mimic")


@pytest.fixture(scope="module")
def source_dataset() -> str:
    os.makedirs(DATASETS_DOWNLOAD_DIR, exist_ok=True)
    path = retrieve_file_path(NUCLEUS_DATASET_PATH, DATASETS_DOWNLOAD_DIR)
    assert os.path.isfile(path)
    os.environ["PYTHONUNBUFFERED"] = "1"
    return path


def _workflow_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../.."))


@pytest.fixture(scope="module")
def physx_annotated_dataset(source_dataset) -> str:
    """Annotate the nucleus source dataset ONCE under the default (PhysX) physics backend.

    ``test_annotate_and_generate_on_newton`` (below) shows that cross-backend *replay* -- restoring a
    PhysX-recorded initial state and open-loop replaying its recorded actions under Newton dynamics --
    yields 0/10 in all four solver modes, which short-circuits before the generate stage ever runs.

    Generation is a different operation: it slices the source demo into object-centric subtask
    segments, transforms each segment to the new scene's object poses, and *executes it fresh* under
    whichever physics backend the env is configured with, filtering on success. It does not require the
    source demo's actions to replay verbatim under the target backend, so a PhysX-annotated source is a
    valid feed for a Newton generate run. This fixture produces that source once and is shared (module
    scope) by every ``test_generate_on_newton[<solver>]`` case.

    PhysX annotation itself is not under test here -- it is proven to work by this branch's earlier
    regressions (Task 7/9 passing runs of ``test_generate_dataset_franka_state.py``) -- so a zero yield
    is treated as a hard failure, not an xfail.
    """
    annotated = os.path.join(DATASETS_DOWNLOAD_DIR, "annotated_physx.hdf5")
    result = run_script(
        [
            sys.executable,
            os.path.join(_workflow_root(), "scripts/imitation_learning/isaaclab_mimic/annotate_demos.py"),
            "--task",
            TASK,
            "--input_file",
            source_dataset,
            "--output_file",
            annotated,
            "--auto",
        ],
        timeout=_SUBPROCESS_TIMEOUT,
    )
    print(f"annotate_demos (PhysX default) stdout:\n{result.stdout}")
    print(f"annotate_demos (PhysX default) stderr:\n{result.stderr}")
    assert "Annotation yield:" in result.stdout, (
        "PhysX annotate_demos (the proven-working path) did not complete cleanly:\n"
        f"stdout tail: {result.stdout[-3000:]}\nstderr tail: {result.stderr[-3000:]}"
    )
    yield_line = next(line for line in result.stdout.splitlines() if line.startswith("Annotation yield:"))
    exported_str, total_str = yield_line.split(":")[1].strip().split("/")
    exported = int(exported_str)
    total = int(total_str.split()[0])
    assert exported >= 1, (
        f"PhysX annotation yielded {exported}/{total} episodes. PhysX annotation is proven to work by"
        " this branch's earlier regressions -- a zero yield here would be a real regression, not the"
        " expected cross-backend-replay finding this file otherwise documents."
    )
    return annotated


@pytest.mark.parametrize("solver", SOLVER_MODES)
def test_generate_on_newton(physx_annotated_dataset, solver):
    """Run MimicGen generation on Newton (all four solver modes) from a PhysX-annotated source.

    Unlike ``test_annotate_and_generate_on_newton``, this does not depend on cross-backend replay
    succeeding: it feeds a known-good PhysX-annotated source straight into ``generate_dataset.py``
    configured for Newton, so the generate stage -- and the Task 6 ``physics_args`` metadata stamp --
    actually executes on Newton for the first time.

    Termination semantics (see the ``_GENERATION_SUBPROCESS_TIMEOUT`` comment above): the franka stack
    mimic cfg sets ``generation_guarantee=True``, so ``env_loop`` (generation.py) loops until either
    ``num_success >= generation_num_trials`` or ``num_failures >= datagen_config.max_num_failures``
    (25 here), whichever comes first -- a zero-success run bounds itself at 25 failed attempts instead
    of running forever. ``run_script``'s SIGTERM/SIGKILL timeout is only a safety net for a genuine
    hang/crash. We disambiguate a timeout-kill from a crash by requiring the success-counter line
    ("N/M (x%) successful demos generated") to have printed at least once (each attempt, success or
    failure, prints one) -- its total absence means the process died before completing even one
    attempt, a crash. Its presence with N == 0 is treated as a real zero-success-generation finding and
    xfailed, exactly like the annotate tests below.
    """
    generated = os.path.join(DATASETS_DOWNLOAD_DIR, f"generated_on_newton_{solver}.hdf5")

    result = run_script(
        [
            sys.executable,
            os.path.join(_workflow_root(), "scripts/imitation_learning/isaaclab_mimic/generate_dataset.py"),
            "--task",
            TASK,
            "--input_file",
            physx_annotated_dataset,
            "--output_file",
            generated,
            "--generation_num_trials",
            "2",
            "--num_envs",
            "2",
            "--physics_preset",
            "newton_mjwarp",
            "--solver",
            solver,
        ],
        timeout=_GENERATION_SUBPROCESS_TIMEOUT,
    )
    print(f"generate_dataset (--solver {solver}) stdout:\n{result.stdout}")
    print(f"generate_dataset (--solver {solver}) stderr:\n{result.stderr}")

    counter_matches = [m for m in (_SUCCESS_COUNTER_RE.match(line) for line in result.stdout.splitlines()) if m]
    assert counter_matches, (
        f"generate_dataset under --solver {solver} produced no success-counter output (crashed before"
        f" completing a single generation attempt, or was killed by the {_GENERATION_SUBPROCESS_TIMEOUT}s"
        " timeout before its first attempt finished):\n"
        f"stdout tail: {result.stdout[-3000:]}\nstderr tail: {result.stderr[-3000:]}"
    )
    last_match = counter_matches[-1]
    num_success, num_attempts = int(last_match.group(1)), int(last_match.group(2))

    if num_success == 0:
        pytest.xfail(
            f"generation yielded {num_success}/{num_attempts} successful demos under --solver {solver}"
            " (a zero-success-generation finding for the fidelity report, not a harness/crash bug)."
        )

    # --- generated dataset carries the physics stamp (Task 6) ---
    assert os.path.isfile(generated), (
        f"generate_dataset reported {num_success}/{num_attempts} successes under --solver {solver} but"
        f" produced no output file:\nstdout tail: {result.stdout[-3000:]}\nstderr tail:"
        f" {result.stderr[-3000:]}"
    )
    with h5py.File(generated, "r") as f:
        env_args = json.loads(f["data"].attrs["env_args"])
        assert "physics_args" in env_args, "physics_args missing from generated dataset metadata"
        expected_sap = solver.startswith("sap")
        assert (env_args["physics_args"]["backend"] == "sap") == expected_sap


@pytest.mark.parametrize("solver", SOLVER_MODES)
def test_annotate_and_generate_on_newton(source_dataset, solver):
    annotated = os.path.join(DATASETS_DOWNLOAD_DIR, f"annotated_{solver}.hdf5")
    generated = os.path.join(DATASETS_DOWNLOAD_DIR, f"generated_{solver}.hdf5")

    # --- annotate (retry-replay under Newton dynamics) ---
    result = run_script(
        [
            sys.executable,
            os.path.join(_workflow_root(), "scripts/imitation_learning/isaaclab_mimic/annotate_demos.py"),
            "--task",
            TASK,
            "--input_file",
            source_dataset,
            "--output_file",
            annotated,
            "--auto",
            "--retries",
            "5",
            "--physics_preset",
            "newton_mjwarp",
            "--solver",
            solver,
        ],
        timeout=_SUBPROCESS_TIMEOUT,
    )
    # Print the subprocess output so the run log carries the per-episode replay
    # evidence (yield line, attempts histogram) even when the test xfails.
    print(f"annotate_demos (--solver {solver}) stdout:\n{result.stdout}")
    print(f"annotate_demos (--solver {solver}) stderr:\n{result.stderr}")
    assert "Annotation yield:" in result.stdout, (
        f"annotate_demos did not complete cleanly under --solver {solver}:\n"
        f"stdout tail: {result.stdout[-3000:]}\nstderr tail: {result.stderr[-3000:]}"
    )
    yield_line = next(line for line in result.stdout.splitlines() if line.startswith("Annotation yield:"))
    exported_str, total_str = yield_line.split(":")[1].strip().split("/")
    exported = int(exported_str)
    total = int(total_str.split()[0])
    if exported == 0:
        pytest.xfail(
            f"cross-backend replay yielded {exported}/{total} annotated episodes under"
            f" --solver {solver} even with 5 retries — a real finding for the fidelity report, not"
            " a harness bug. Record it and move on."
        )

    # --- generate a small batch from the annotated demos ---
    result = run_script(
        [
            sys.executable,
            os.path.join(_workflow_root(), "scripts/imitation_learning/isaaclab_mimic/generate_dataset.py"),
            "--task",
            TASK,
            "--input_file",
            annotated,
            "--output_file",
            generated,
            "--generation_num_trials",
            "2",
            "--num_envs",
            "2",
            "--physics_preset",
            "newton_mjwarp",
            "--solver",
            solver,
        ],
        timeout=_SUBPROCESS_TIMEOUT,
    )
    print(f"generate_dataset (--solver {solver}) stdout:\n{result.stdout}")
    print(f"generate_dataset (--solver {solver}) stderr:\n{result.stderr}")
    assert os.path.isfile(generated), (
        f"generate_dataset produced no output under --solver {solver}:\n"
        f"stdout tail: {result.stdout[-3000:]}\nstderr tail: {result.stderr[-3000:]}"
    )

    # --- generated dataset carries the physics stamp (Task 6) ---
    with h5py.File(generated, "r") as f:
        env_args = json.loads(f["data"].attrs["env_args"])
        assert "physics_args" in env_args, "physics_args missing from generated dataset metadata"
        expected_sap = solver.startswith("sap")
        assert (env_args["physics_args"]["backend"] == "sap") == expected_sap
